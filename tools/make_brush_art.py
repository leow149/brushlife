#!/usr/bin/env python3
"""Turns the stylised brush-head image (sonicare.png) into the vector paths used by the app.

Needs numpy, scipy, pillow, potracer (pip install --target <dir> ...) and PYTHONPATH pointing at that dir.
Usage: make_brush_art.py <sonicare.png> <out BrushArt.kt> <out preview dir>

Steps: silhouette by flood-filling the white background, cut the cone off above the grey
"stub" at the bottom, drop the text/logo by filling the body solid, split the tufts by hue,
compress the long neck, trace everything to Bezier paths.
"""
import sys, numpy as np, potrace
from PIL import Image
from scipy import ndimage as ndi

src, out_kt, prev_dir = sys.argv[1:4]
a = np.asarray(Image.open(src).convert("RGB")).astype(float) / 255
H, W, _ = a.shape
mx = a.max(2); mn = a.min(2); d = mx - mn + 1e-9
r, g, b = a[..., 0], a[..., 1], a[..., 2]
hue = np.where(mx == r, ((g - b) / d) % 6, np.where(mx == g, (b - r) / d + 2, (r - g) / d + 4)) / 6
sat = d / np.maximum(mx, 1e-9); val = mx

# silhouette
bg_cand = (a.min(2) > 228 / 255)
lab, n = ndi.label(bg_cand)
border = (set(lab[0]) | set(lab[-1]) | set(lab[:, 0]) | set(lab[:, -1])) - {0}
S = ~np.isin(lab, list(border))
S = ndi.binary_opening(S, iterations=1)
lab, n = ndi.label(S); S = lab == 1 + int(np.argmax(ndi.sum(S, lab, range(1, n + 1))))
S = ndi.binary_fill_holes(S)
CUT_Y = 1138                       # flat lower edge of the cone; everything below is the stub
S[CUT_Y + 1:] = False

# tufts (head region only)
head = np.zeros_like(S); head[:470] = True
blue = S & head & (hue > .5) & (hue < .68) & (sat > .28) & (val > .45)
green = S & head & (hue > .17) & (hue < .42) & (sat > .30) & (val > .45)
white = S & head & (sat < .22) & (val > .75)
def clean(x, minpx=200):
    x = ndi.binary_opening(x, iterations=1); lab, n = ndi.label(x); out = np.zeros_like(x)
    for i in range(1, n + 1):
        if (lab == i).sum() >= minpx: out |= ndi.binary_fill_holes(lab == i)
    return out
blue, green, white = clean(blue), clean(green), clean(white)

# compress the neck (rows 470..860) so the picture is not extremely thin
y0 = int(np.where(S.any(1))[0][0]) - 4
segs = [(y0, 470, 1.0), (470, 860, 0.45), (860, CUT_Y + 2, 1.0)]
src_rows = []
for s, e, f in segs:
    src_rows += list(np.linspace(s, e - 1, int((e - s) * f)))
src_rows = np.array(src_rows).round().astype(int)
cols = np.where(S.any(0))[0]; x0, x1 = cols[0] - 6, cols[-1] + 7
def warp(m): return m[src_rows][:, x0:x1]
Sw, Bw, Gw, Ww = map(warp, (S, blue, green, white))
OH, OW = Sw.shape

def smooth(m, s): return ndi.gaussian_filter(np.pad(m.astype(float), 20), s)[20:-20, 20:-20] > .5
Sw = smooth(Sw, 2.0)
Bw, Gw, Ww = smooth(Bw, 1.2), smooth(Gw, 1.2), smooth(Ww, 1.2)

def trace(mask, turd=30, alpha=1.2, tol=0.6):
    pl = potrace.Bitmap(~mask).trace(turdsize=turd, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY,
                                     alphamax=alpha, opticurve=True, opttolerance=tol)
    d = []
    for c in pl:
        s = c.start_point; d.append(f"M{s.x:.1f},{s.y:.1f}")
        for seg in c.segments:
            if seg.is_corner: d.append(f"L{seg.c.x:.1f},{seg.c.y:.1f}L{seg.end_point.x:.1f},{seg.end_point.y:.1f}")
            else: d.append(f"C{seg.c1.x:.1f},{seg.c1.y:.1f} {seg.c2.x:.1f},{seg.c2.y:.1f} {seg.end_point.x:.1f},{seg.end_point.y:.1f}")
        d.append("Z")
    return "".join(d)
body, pb, pg, pw = trace(Sw), trace(Bw), trace(Gw), trace(Ww)

with open(out_kt, "w") as f:
    f.write("// Generated by tools/make_brush_art.py from the stylised brush-head image. Do not edit by hand.\n")
    f.write("package de.leow149.brushlife\n\n")
    f.write("/** SVG path data for the brush-head picture, all in the same %d x %d coordinate space. */\n" % (OW, OH))
    f.write("object BrushArt {\n")
    f.write(f"    const val WIDTH = {OW}f\n    const val HEIGHT = {OH}f\n")
    for name, p in (("BODY", body), ("BLUE", pb), ("GREEN", pg), ("WHITE", pw)):
        f.write(f'    const val {name} = "{p}"\n')
    f.write("}\n")
print("size", OW, OH, "path chars", len(body), len(pb), len(pg), len(pw))
import os; os.makedirs(prev_dir, exist_ok=True)
open(os.path.join(prev_dir, "paths.txt"), "w").write(f"{OW} {OH}\n{body}\n{pb}\n{pg}\n{pw}\n")
